// Mock 325's two identity blocks under the profile card: ONE "Working toward" line (the
// aspiration), then a short About with the interest tags.
//
// "Working toward", "working on" and the career headline used to be three lines saying one thing
// (CODE_PROMPT_ui_streamline.md §14). The aspiration is now whichever of them the person filled in,
// in that order of ambition, and About picks up "working on" only when it says something the
// aspiration didn't. About replaces the bio (pre-submission F13) — it is built from what they told
// /edit-identity, so there is no second free-text field to keep honest.
//
// Your own empty block is one gentle prompt into /edit-identity; anyone else's empty — or
// dial-hidden — block is not drawn at all.

/** The single aspiration line: working toward, else the career headline, else working on. */
export function aspirationOf(identity: ProfileIdentity | null): string | null {
  if (!identity || !identity.identity_visible) return null;
  return identity.working_toward?.trim() || identity.career_goal?.trim() || identity.working_on?.trim() || null;
}

function AnthemChip({ anthem }: { anthem: Anthem }) {
  const url = anthem.url ?? null;
  const body = (
    <View style={styles.anthem}>
      <View style={styles.art}>
        <Icon name="music" size={14} color={Colors.ink} />
      </View>
      <View style={styles.anthemText}>
        <Text style={styles.anthemTitle} numberOfLines={1}>
          {anthem.title}
        </Text>
        <Text style={styles.anthemSub} numberOfLines={1}>
          {anthem.artist ? `${anthem.artist} · ` : ''}my anthem
        </Text>
      </View>
      {url ? <Ionicons name="open-outline" size={13} color={Colors.textTertiary} /> : null}
    </View>
  );
  if (!url) return body;
  return (
    // The server only stores an https open.spotify.com / music.apple.com link (0272), so this
    // can't be steered anywhere else.
    <Pressable
      onPress={() => void Linking.openURL(url).catch(() => {})}
      accessibilityRole="link"
      accessibilityLabel={`Play ${anthem.title}`}>
      {body}
    </Pressable>
  );
}

/** Mock 325's `.wt` — the one line of what this person wants to be. */
export function WorkingToward({ identity }: { identity: ProfileIdentity | null }) {
  const router = useRouter();
  if (!identity) return null;
  const aspiration = aspirationOf(identity);

  if (!aspiration) {
    if (!identity.is_self) return null;
    return (
      <Pressable
        style={[styles.wt, styles.prompt]}
        onPress={() => router.push('/edit-identity' as never)}
        accessibilityRole="button"
        accessibilityLabel="Add what you're working toward">
        <Ionicons name="sparkles-outline" size={15} color={Colors.ember} />
        <View style={styles.promptText}>
          <Text style={styles.promptTitle}>What are you locking in for?</Text>
          <Text style={styles.promptSub}>Add what you&apos;re working toward — it leads your profile.</Text>
        </View>
        <Ionicons name="chevron-forward" size={14} color={Colors.textTertiary} />
      </Pressable>
    );
  }

  const body = (
    <View style={styles.wt}>
      <Text style={styles.wtKey}>Working toward</Text>
      <Text style={styles.wtValue}>{aspiration}</Text>
    </View>
  );
  if (!identity.is_self) return body;
  // Route typings are generated by Metro, so a new screen isn't in them until the next start.
  return (
    <Pressable onPress={() => router.push('/edit-identity' as never)} accessibilityRole="button" accessibilityLabel={`Working toward ${aspiration}. Edit`}>
      {body}
    </Pressable>
  );
}

/** Mock 325's `.about` — a short line, the anthem, the interest tags. */
export function IdentityAbout({ identity }: { identity: ProfileIdentity | null }) {
  if (!identity || !identity.identity_visible) return null;

  const aspiration = aspirationOf(identity);
  const on = identity.working_on?.trim();
  const line = on && on !== aspiration ? on : null;
  const anthem = identity.anthem?.title ? identity.anthem : null;
  const interests = (identity.interests ?? []).filter(Boolean);
  if (!line && !anthem && interests.length === 0) return null;

  return (
    <View style={styles.about}>
      <Text style={styles.aboutKey}>About</Text>
      {line ? <Text style={styles.aboutText}>{line}</Text> : null}
      {interests.length > 0 ? (
        <View style={styles.tags}>
          {interests.map((t) => (
            <View key={t} style={styles.tag}>
              <Text style={styles.tagText}>{t}</Text>
            </View>
          ))}
        </View>
      ) : null}
      {anthem ? (
        <View style={styles.anthemWrap}>
          <AnthemChip anthem={anthem} />
        </View>
      ) : null}
    </View>
  );
}

