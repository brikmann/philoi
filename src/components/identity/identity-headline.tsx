import { useRouter } from 'expo-router';
import { Pressable, StyleSheet, Text } from 'react-native';

import { Colors, Fonts } from '@/constants/theme';
import type { ProfileIdentity } from '@/types/social';

// Mock 283's `.pf-head` — "future sports physio" in gold, directly under the name. The spec calls
// this the most important identity string on the page, so it reads as a statement rather than a
// form field: no label, no quotes, just the line.
//
// Your own empty headline is an invitation (the same quiet italic as the bio's "＋ add a bio");
// someone else's empty — or dial-hidden — headline is simply absent.
export function IdentityHeadline({ identity }: { identity: ProfileIdentity | null }) {
  const router = useRouter();
  if (!identity) return null;

  const career = identity.career_goal?.trim();
  if (career) {
    return identity.is_self ? (
      // Route typings are generated by Metro, so a new screen isn't in them until the next start.
      <Pressable onPress={() => router.push('/edit-identity' as never)} hitSlop={6}>
        <Text style={styles.headline} numberOfLines={1}>
          {career}
        </Text>
      </Pressable>
    ) : (
      <Text style={styles.headline} numberOfLines={1}>
        {career}
      </Text>
    );
  }

  if (!identity.is_self) return null;
  return (
    <Pressable
      onPress={() => router.push('/edit-identity' as never)}
      hitSlop={6}
      accessibilityRole="button"
      accessibilityLabel="Add what you wanna be">
      <Text style={[styles.headline, styles.empty]} numberOfLines={1}>
        ＋ what are you locking in for?
      </Text>
    </Pressable>
  );
}

const styles = StyleSheet.create({
  headline: {
    fontFamily: Fonts.bodyBold,
    fontSize: 13,
    color: Colors.ember,
    marginTop: 3,
  },
  empty: {
    fontFamily: Fonts.body,
    fontStyle: 'italic',
    color: Colors.textTertiary,
  },
});
