-- 0219 — the Flame Pass mints two Mythics, and sells none of its season looks. 💰 economy fix
--
-- Two holes, one economy:
--
-- 1. THE PASS FLOODED MYTHICS. Eight Emberfall pass items were Mythic — the L0 flare, L25 banner,
--    L40 particle, L50 halo + sting, L75 card, L100 medal + title. At $8.99 that is a Mythic for
--    ~$1.12, while the Promethean Vault charges 8,000 embers at 12% for one. Nobody opens the vault.
--    Now exactly two, both earned by climbing, both permanent pieces of the profile:
--      • relic-emberfall        L90  — the Emberfall Relic, in the profile showcase     (legendary → MYTHIC)
--      • medal-emberfall-crown  L100 — the Emberfall Crown, the small badge by your name (stays MYTHIC)
--    Seven demoted mythic → legendary: flare-emberfall-ascendant, banner-emberfall-mythic,
--    particle-void-smoke, halo-emberfall-mythic, sfx-emberfall-strike, card-emberfall-mythic,
--    title-forged-in-ember. Ember drip, box weights and the vault price are untouched.
--
--    Rarity lives in four places server-side and they must agree (0213 asserted it):
--      cosmetic_rarity (sale price)    — FULL re-seed from catalog.ts below, because
--                                        scripts/check-cosmetic-rarity.js reads the NEWEST seed as the
--                                        whole table. Regenerate with `--print-seed`.
--      pass_track_rewards.item_rarity  — what claim_pass_level grants at (L25/40/50/75/90/100).
--      box_droppable_items.rarity      — particle-void-smoke is ALSO a vault drop. It moves from the
--                                        mythic pool (5 → 4 items) to legendary (14 → 15). Per-tier
--                                        weights (economy_config.box_odds) do not change.
--      grant_level_zero_unlock         — hands the flare 'mythic' as a literal. Left alone: that value
--                                        only prices the dupe auto-salvage, and the L0 grant is
--                                        once-per-season (pass_claims) for a pass-only item, so the
--                                        dupe path is unreachable. Not worth restating a live
--                                        purchase-path function for.
--
-- 2. PASS LOOKS WERE SELLABLE. salvage_cosmetic fenced source='earned' (0213) but pass grants are
--    source='forge_pass' (0074), so a season's looks could be dumped for embers. Season looks are
--    prestige, not currency — they now refuse like earned items. source='box' and 'paid' stay
--    sellable: vault drops and direct buys are meant to be.
--
-- Restated from live prosrc (md5 7822856d… = 0213's body, verified identical 2026-09-24).
-- Signature unchanged, so installed builds keep working; the only visible change is the refusal.
--
-- NOTE: no explicit begin/commit — the migration runs in its own transaction.

do $guard$
declare
  v_md5 text;
begin
  select md5(p.prosrc) into v_md5 from pg_proc p
  where p.oid = 'public.salvage_cosmetic(text, text)'::regprocedure;
  if v_md5 is distinct from '7822856d3ade49d1302320754f6faafc' then
    raise exception '0219: salvage_cosmetic changed since it was read (md5 %). Re-restate from live prosrc.', v_md5;
  end if;
end;
$guard$;

