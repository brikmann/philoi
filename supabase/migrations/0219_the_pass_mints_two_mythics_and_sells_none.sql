-- ───────────────────────────── the sale ─────────────────────────────

create or replace function salvage_cosmetic(p_key text, p_rarity text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user uuid := auth.uid();
  v_row cosmetics_owned;
  v_rarity text;
  v_payout int;
begin
  if v_user is null then raise exception 'Not signed in'; end if;

  -- p_rarity is VESTIGIAL (0213). It stays in the signature only because installed builds send it;
  -- it is never read. The price is the server's.

  if p_key = any (default_cosmetic_keys()) then
    raise exception 'Starter items are permanent and cannot be sold.';
  end if;

  -- 0212 — kept as a belt to the source rule below.
  if p_key like 'title-campfire-finisher:%' then
    raise exception 'Campfire finisher titles are permanent and cannot be sold.';
  end if;

  -- Locked so a double-tap cannot pay twice for one row.
  select * into v_row from cosmetics_owned
  where user_id = v_user and cosmetic_key = p_key
  for update;

  if v_row.id is null then
    raise exception 'You do not own this item';
  end if;

  -- 0213 — THE fence. Season titles, relics, medals, finisher titles: prestige, not currency.
  if v_row.source = 'earned' then
    raise exception 'Earned items are permanent and cannot be sold.';
  end if;

  -- 0219 — and the season's pass looks with them. A Flame Pass cosmetic is never re-issued; selling
  -- it turned the pass into an ember mint. Box drops and direct buys stay sellable.
  if v_row.source = 'forge_pass' then
    raise exception 'Season pass items are permanent and cannot be sold.';
  end if;

  v_rarity := coalesce(
    v_row.rarity_override,
    (select cr.rarity from cosmetic_rarity cr where cr.cosmetic_key = p_key)
  );
  if v_rarity is null then
    raise exception 'This item cannot be sold right now (no known rarity for %).', p_key;
  end if;

  v_payout := ((select value from economy_config where key = 'salvage_embers') ->> v_rarity)::int;
  if v_payout is null then
    raise exception 'No salvage price for rarity %', v_rarity;
  end if;

  delete from equipped_loadout where user_id = v_user and cosmetic_key = p_key;
  delete from cosmetics_owned where id = v_row.id;
  perform economy_move_embers(v_user, v_payout, 'salvage', null);
  -- `rarity` is new and additive: the rarity actually paid, so a client can stop guessing.
  return jsonb_build_object('embers', v_payout, 'rarity', v_rarity);
end;
$$;

-- ───────────────────────────── assertions ─────────────────────────────

do $assert$
declare
  v_src text;
  v_n int;
  v_keys text;
  v_owner uuid;
  v_key text;
  v_refused text;
  v_before int;
begin
  -- The pass's Mythics are exactly the two capstones, across the whole Emberfall pass set (the L0
  -- flare is granted by literal, not from pass_track_rewards, so the set is checked by key too).
  select string_agg(cosmetic_key, ',' order by cosmetic_key) into v_keys from cosmetic_rarity
  where rarity = 'mythic' and cosmetic_key in (
    'flame-emberfall', 'halo-emberfall', 'card-emberfall', 'title-kindled-by-emberfall',
    'flare-emberfall-ascendant', 'flame-forge', 'title-dialed-in', 'banner-ashfall',
    'banner-emberfall-mythic', 'halo-emberfall-mythic', 'sfx-emberfall-strike', 'card-emberfall-mythic',
    'relic-emberfall', 'medal-emberfall-crown', 'title-s1-the-relentless', 'title-forged-in-ember',
    'particle-void-smoke'
  );
  if v_keys is distinct from 'medal-emberfall-crown,relic-emberfall' then
    raise exception '0219: the pass mythics are [%], expected medal-emberfall-crown,relic-emberfall', v_keys;
  end if;

  select string_agg(item_key, ',' order by item_key) into v_keys from pass_track_rewards
  where item_rarity = 'mythic';
  if v_keys is distinct from 'medal-emberfall-crown,relic-emberfall' then
    raise exception '0219: pass_track_rewards mints mythics [%], expected the two capstones', v_keys;
  end if;

  -- The three rarity copies still agree (0213's invariant, re-checked after moving them).
  if exists (
    select 1 from box_droppable_items d
    left join cosmetic_rarity cr on cr.cosmetic_key = d.item_key
    where cr.rarity is distinct from d.rarity
  ) then
    raise exception '0219: box_droppable_items disagrees with cosmetic_rarity';
  end if;
  if exists (
    select 1 from pass_track_rewards p
    left join cosmetic_rarity cr on cr.cosmetic_key = p.item_key
    where p.item_key is not null and cr.rarity is distinct from p.item_rarity
  ) then
    raise exception '0219: pass_track_rewards disagrees with cosmetic_rarity';
  end if;

  -- The vault still has a mythic pool to roll into.
  select count(*) into v_n from box_droppable_items where rarity = 'mythic';
  if v_n < 1 then raise exception '0219: the vault mythic pool is empty'; end if;

  -- Both fences are in the body.
  select p.prosrc into v_src from pg_proc p where p.oid = 'public.salvage_cosmetic(text, text)'::regprocedure;
  if v_src not like '%v_row.source = ''earned''%' then
    raise exception '0219: salvage_cosmetic lost the earned fence';
  end if;
  if v_src not like '%v_row.source = ''forge_pass''%' then
    raise exception '0219: salvage_cosmetic does not refuse forge_pass items';
  end if;
  if v_src ~ '->>\s*p_rarity' then
    raise exception '0219: salvage_cosmetic prices off p_rarity again';
  end if;

  -- Exercised, not just grepped: sell a real forge_pass row as its owner and expect the refusal.
  -- A refusal raises, so nothing is deleted or paid; the row count is checked either way.
  select user_id, cosmetic_key into v_owner, v_key from cosmetics_owned
  where source = 'forge_pass' order by cosmetic_key limit 1;
  if v_owner is not null then
    select count(*) into v_before from cosmetics_owned where source = 'forge_pass';
    perform set_config('request.jwt.claims', json_build_object('sub', v_owner, 'role', 'authenticated')::text, true);
    begin
      perform salvage_cosmetic(v_key, 'mythic');
      v_refused := null;
    exception when others then
      v_refused := sqlerrm;
    end;
    perform set_config('request.jwt.claims', '', true);
    if v_refused is distinct from 'Season pass items are permanent and cannot be sold.' then
      raise exception '0219: selling forge_pass % was not refused (got: %)', v_key, coalesce(v_refused, 'a sale');
    end if;
    select count(*) into v_n from cosmetics_owned where source = 'forge_pass';
    if v_n <> v_before then raise exception '0219: a refused sale still removed a pass item'; end if;
  end if;

  -- One signature, callable by a signed-in client, not by anon (create or replace keeps grants).
  select count(*) into v_n from pg_proc p join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public' and p.proname = 'salvage_cosmetic';
  if v_n <> 1 then raise exception '0219: salvage_cosmetic has % overloads', v_n; end if;
  if not has_function_privilege('authenticated', 'public.salvage_cosmetic(text, text)', 'execute') then
    raise exception '0219: authenticated lost execute on salvage_cosmetic';
  end if;
  if has_function_privilege('anon', 'public.salvage_cosmetic(text, text)', 'execute') then
    raise exception '0219: anon can execute salvage_cosmetic';
  end if;
end;
$assert$;
