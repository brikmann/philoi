-- ───────────────────────────── B · the two season-window tests ─────────────────────────────

/**
 * Unbroken Season: a completed lock-in on EVERY whole local day of [p_starts, p_ends). A day the
 * window only partly covers in the user's zone (the opening and closing edges, off by their offset
 * from the season clock) is not required — that would make the medal depend on where you live.
 * A zone Postgres doesn't know falls back to UTC rather than throwing.
 */
create or replace function season_was_unbroken(p_user uuid, p_starts timestamptz, p_ends timestamptz)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  v_tz text;
  v_open timestamp;
  v_first date;
  v_last date;
  v_days int;
begin
  if p_user is null or p_starts is null or p_ends is null or p_ends <= p_starts then return false; end if;

  select nullif(p.timezone, '') into v_tz from profiles p where p.id = p_user;
  begin
    perform now() at time zone coalesce(v_tz, 'UTC');
  exception when others then
    v_tz := null;
  end;
  v_tz := coalesce(v_tz, 'UTC');

  -- First and last WHOLE local days inside the window.
  v_open := p_starts at time zone v_tz;
  v_first := case when v_open = date_trunc('day', v_open) then v_open::date else v_open::date + 1 end;
  v_last := (p_ends at time zone v_tz)::date - 1;
  if v_last < v_first then return false; end if;

  select count(distinct (s.started_at at time zone v_tz)::date) into v_days
  from lock_in_sessions s
  where s.user_id = p_user
    and s.status = 'completed'
    and (s.started_at at time zone v_tz)::date between v_first and v_last;

  return v_days >= (v_last - v_first + 1);
end;
$$;

/**
 * The Undefeated: at least THREE campfire races settled in the window, each against a field of two
 * or more, and first (final_rank = 1, ties included) in every one. A race of one is not a race —
 * solo challenges never count, as wins or as losses. Duels (mode 'h2h') are not campfire races
 * (0212's scope). A race is in the season by when it ENDED.
 */
create or replace function season_was_undefeated(p_user uuid, p_starts timestamptz, p_ends timestamptz)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  with races as (
    select p.final_rank,
           (select count(*) from challenge_participants q
             where q.challenge_id = c.id and q.state = 'accepted' and q.final_rank is not null) as field
    from challenge_participants p
    join social_challenges c on c.id = p.challenge_id
    where p.user_id = p_user
      and p.state = 'accepted'
      and p.final_rank is not null
      and c.status = 'completed'
      and c.circle_id is not null
      and c.mode <> 'h2h'
      and coalesce(c.ends_at, c.created_at) >= p_starts
      and coalesce(c.ends_at, c.created_at) < p_ends
  )
  select count(*) >= 3 and count(*) filter (where final_rank > 1) = 0
  from races
  where field >= 2;
$$;

revoke all on function season_was_unbroken(uuid, timestamptz, timestamptz) from public, anon, authenticated;
revoke all on function season_was_undefeated(uuid, timestamptz, timestamptz) from public, anon, authenticated;

-- ───────────────────────────── B + D · the global closer ─────────────────────────────
-- 0222's body. Changed: the banner is priced at its own rarity (§D), and the global pass grants
-- Unbroken Season and The Undefeated (§B). Nothing else differs.

create or replace function public.close_season_scope(p_season text, p_scope text, p_key text default null::text)
 returns integer
 language plpgsql
 security definer
 set search_path to 'public'
as $function$
declare
  v_paid int := 0;
  v_is_global boolean := (p_scope = 'global');
  r record;
  v_pct numeric;
  v_band text;
  v_cut text;
  v_title season_titles;
  v_stamp text;
  v_why text;
  v_starts timestamptz;
  v_ends timestamptz;
begin
  insert into season_closures (season_id, scope, scope_key)
  values (p_season, p_scope, coalesce(p_key, ''))
  on conflict do nothing;
  if not found then return 0; end if;

  -- 0201 — the season_settled notification below speaks for the participation badge.
  perform set_config('philoi.quiet_badge', 'on', true);

  -- 0223 — the season window, for the two season-long tests below. Only the season the clock is on
  -- has one; closing any other id simply skips them.
  if season_config() ->> 'id' = p_season then
    v_starts := (season_config() ->> 'starts_at')::timestamptz;
    v_ends := (season_config() ->> 'ends_at')::timestamptz;
  end if;

  for r in
    select p.id as user_id,
           row_number() over (order by universal_score(p.id) desc) as rank,
           count(*) over () as board_size
    from profiles p
    where not p.is_demo and not p.is_disabled
      and (p_scope <> 'uni' or (p.university = p_key and p.university_email_verified))
  loop
    v_pct := r.rank::numeric / greatest(r.board_size, 1);
    perform grant_reward(r.user_id, 'season', 1.0, 90, r.board_size::int, v_pct, true, null);

    -- Everyone who met the floor keeps a dated participation badge (§4b).
    perform economy_grant_badge(r.user_id, 'season-participant-' || p_season, 'Season ' || p_season || ' · took part');

    v_band := season_band(r.rank::int, r.board_size::int);

    -- 0222 — the placement ladder is GLOBAL (Noah, 2026-10-02). A campus board still pays its XP,
    -- badge and notification above and below, and prints its own ladder in 0187's closer.
    if v_is_global and v_band is not null then
      -- The 5% cut lives HERE, not in season_band(): installed builds label bands by name, and a
      -- band they have never seen would render blank. Logged under the band season_band() gave.
      v_cut := case when v_band = 'p10' and v_pct <= 0.05 then 'p5' else v_band end;
      select * into v_title from season_titles st where st.season_id = p_season and st.band = v_cut;

      if v_title.cosmetic_key is not null then
        v_stamp := '🌍 GLOBAL ' ||
          case v_cut
            when 'rank_1' then '#1'
            when 'rank_2' then '#2'
            when 'rank_3' then '#3'
            when 'p1' then '· TOP 1%'
            when 'p5' then '· TOP 5%'
            when 'p10' then '· TOP 10%'
            when 'p25' then '· TOP 25%'
            else '· TOP 50%'
          end || ' · ' || p_season;
        v_why := 'Season ' || p_season || ' · global placement #' || r.rank;

        -- The rarity is the catalog's (cosmetic_rarity), so no override: the finisher ladder's
        -- rarities are explicit, and the old global notch would have mis-priced every one of them.
        perform economy_grant_title(r.user_id, v_title.cosmetic_key, v_why, v_stamp, null);
        perform season_log_grant(p_season, r.user_id, p_scope, v_band, 'title', v_title.cosmetic_key,
                                 v_title.title, v_title.rarity, true, null);

        if v_title.medal_key is not null then
          perform economy_grant_cosmetic(r.user_id, v_title.medal_key, null,
            coalesce((select cr.rarity from cosmetic_rarity cr where cr.cosmetic_key = v_title.medal_key), v_title.rarity),
            'earned', v_why);
          -- "Surtur · Emberfall 1st Finisher" → the medal is "Emberfall 1st Finisher".
          perform season_log_grant(p_season, r.user_id, p_scope, v_band, 'medal', v_title.medal_key,
                                   regexp_replace(v_title.title, '^.* · ', ''),
                                   (select cr.rarity from cosmetic_rarity cr where cr.cosmetic_key = v_title.medal_key),
                                   true, null);
        end if;

        -- The two overlaps mock 249 flagged, both kept.
        if v_cut = 'rank_1' then
          perform economy_grant_title(r.user_id, 'title-ascended', v_why, v_stamp, null);
          perform season_log_grant(p_season, r.user_id, p_scope, v_band, 'title', 'title-ascended',
                                   'Ascended', 'mythic', true, null);
        elsif v_cut = 'p50' and p_season = 'S1' then
          perform economy_grant_title(r.user_id, 'title-s1-warming-up', v_why, v_stamp, null);
          perform season_log_grant(p_season, r.user_id, p_scope, v_band, 'title', 'title-s1-warming-up',
                                   'Warming Up', 'uncommon', true, null);
        end if;

        if v_title.banner_asset is not null then
          -- 0223 — at the BANNER's rarity. The title's (mythic on the podium) priced a dupe banner's
          -- salvage as a mythic.
          perform economy_grant_cosmetic(r.user_id, v_title.banner_asset, 'banner',
            coalesce((select cr.rarity from cosmetic_rarity cr where cr.cosmetic_key = v_title.banner_asset), v_title.rarity),
            'earned', 'Season ' || p_season || ' · ' || v_title.title);
          perform season_log_grant(p_season, r.user_id, p_scope, v_band, 'banner', v_title.banner_asset,
                                   v_title.title || ' Banner',
                                   (select cr.rarity from cosmetic_rarity cr where cr.cosmetic_key = v_title.banner_asset),
                                   true, null);
        end if;
      end if;
    end if;

    -- 0223 — the two season-long achievements. Judged on the GLOBAL pass only, so each person is
    -- considered exactly once (every campus close re-walks the same people).
    if v_is_global and v_starts is not null then
      if season_was_unbroken(r.user_id, v_starts, v_ends) then
        perform economy_grant_cosmetic(r.user_id, 'medal-unbroken-season', null, 'legendary', 'earned',
                                       'Season ' || p_season || ' · a lock-in every single day');
        perform season_log_grant(p_season, r.user_id, p_scope, v_band, 'medal', 'medal-unbroken-season',
                                 'Unbroken Season', 'legendary', true, null);
      end if;
      if season_was_undefeated(r.user_id, v_starts, v_ends) then
        perform economy_grant_title(r.user_id, 'title-the-undefeated',
                                    'Season ' || p_season || ' · every campfire race won', p_season, null);
        perform season_log_grant(p_season, r.user_id, p_scope, v_band, 'title', 'title-the-undefeated',
                                 'The Undefeated', 'epic', true, null);
      end if;
    end if;

    -- 0201 — the season's result, announced once per user per scope.
    perform notify_event(
      array[r.user_id], 'season_settled',
      'Season ' || p_season || case when v_is_global then '' else ' · ' || coalesce(p_key, 'campus') end || ' results are in',
      'You finished #' || r.rank || ' of ' || r.board_size || '. Your rewards are in your inventory.',
      null, null,
      '/inventory', '{}'::jsonb,
      null, null,
      jsonb_build_object('season', p_season, 'scope', p_scope, 'rank', r.rank, 'board_size', r.board_size)
    );

    v_paid := v_paid + 1;
  end loop;

  perform set_config('philoi.quiet_badge', 'off', true);
  return v_paid;
end;
