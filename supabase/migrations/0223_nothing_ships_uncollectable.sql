  if v_uid is not null then
    v_day := (date_trunc('day', v_day at time zone v_tz)) at time zone v_tz;
    if not season_was_unbroken(v_uid, v_day, v_day + interval '1 day') then
      raise exception '0223: season_was_unbroken missed a day with a completed lock-in';
    end if;
    if season_was_unbroken(v_uid, '2001-01-01T00:00:00Z', '2001-01-03T00:00:00Z') then
      raise exception '0223: season_was_unbroken passed days with no lock-in';
    end if;
  end if;

  -- B · season_was_undefeated, both directions, all-time. Anyone who has LOST a field race can
  -- never pass; anyone with 3+ field races and no loss must.
  select count(*) into v_n from (
    select distinct p.user_id from challenge_participants p join social_challenges c on c.id = p.challenge_id
    where p.state = 'accepted' and p.final_rank > 1 and c.status = 'completed' and c.circle_id is not null and c.mode <> 'h2h'
  ) losers where season_was_undefeated(losers.user_id, '-infinity', 'infinity');
  if v_n <> 0 then raise exception '0223: season_was_undefeated passed % players who lost a race', v_n; end if;

  select count(*) into v_n from (
    select p.user_id from challenge_participants p join social_challenges c on c.id = p.challenge_id
    where p.state = 'accepted' and p.final_rank is not null and c.status = 'completed' and c.circle_id is not null
      and c.mode <> 'h2h'
      and (select count(*) from challenge_participants q where q.challenge_id = c.id and q.state = 'accepted' and q.final_rank is not null) >= 2
    group by p.user_id
    having count(*) >= 3 and count(*) filter (where p.final_rank > 1) = 0
  ) unbeaten where not season_was_undefeated(unbeaten.user_id, '-infinity', 'infinity');
  if v_n <> 0 then raise exception '0223: season_was_undefeated failed % players who never lost', v_n; end if;

  -- A · the Vs-Unis close, run: it settles and pays nobody.
  begin
    perform set_config('philoi.suppress_push', 'on', true);
    if close_season_vs_unis('S1') <> 0 then raise exception '0223: close_season_vs_unis reported grants'; end if;
    select count(*) into v_n from cosmetics_owned where acquired_at = now()
      and cosmetic_key in ('title-prometheus-disciples', 'title-keepers-of-the-flame', 'title-champions-of-academia');
    if v_n <> 0 then raise exception '0223: the Vs-Unis close minted % titles', v_n; end if;
    if not exists (select 1 from season_closures where season_id = 'S1' and scope = 'vs_unis') then
      raise exception '0223: the Vs-Unis close no longer records its closure';
    end if;
    raise exception '%', v_marker;
  exception when others then
    get stacked diagnostics v_err = message_text;
    if v_err <> v_marker then raise exception '0223 vs-unis probe: %', v_err; end if;
  end;

  -- B · the global close, run against the live S1 window: Unbroken Season and The Undefeated land
  -- exactly where the tests say, in both directions. (0222's ladder probe already covers the bands.)
  begin
    perform set_config('philoi.suppress_push', 'on', true);
    perform close_season_scope('S1', 'global', null);

    select count(*) into v_n from profiles p
    where not p.is_demo and not p.is_disabled
      and season_was_unbroken(p.id, (v_cfg ->> 'starts_at')::timestamptz, (v_cfg ->> 'ends_at')::timestamptz)
      and not exists (select 1 from cosmetics_owned co where co.user_id = p.id and co.cosmetic_key = 'medal-unbroken-season');
    if v_n <> 0 then raise exception '0223: % unbroken players missed the medal', v_n; end if;
    select count(*) into v_n from cosmetics_owned co
    where co.cosmetic_key = 'medal-unbroken-season' and co.acquired_at = now()
      and not season_was_unbroken(co.user_id, (v_cfg ->> 'starts_at')::timestamptz, (v_cfg ->> 'ends_at')::timestamptz);
    if v_n <> 0 then raise exception '0223: Unbroken Season granted to % players with a dead day', v_n; end if;

    select count(*) into v_n from profiles p
    where not p.is_demo and not p.is_disabled
      and season_was_undefeated(p.id, (v_cfg ->> 'starts_at')::timestamptz, (v_cfg ->> 'ends_at')::timestamptz)
      and not exists (select 1 from cosmetics_owned co where co.user_id = p.id and co.cosmetic_key = 'title-the-undefeated');
    if v_n <> 0 then raise exception '0223: % undefeated players missed the title', v_n; end if;
    select count(*) into v_n from cosmetics_owned co
    where co.cosmetic_key = 'title-the-undefeated' and co.acquired_at = now()
      and not season_was_undefeated(co.user_id, (v_cfg ->> 'starts_at')::timestamptz, (v_cfg ->> 'ends_at')::timestamptz);
    if v_n <> 0 then raise exception '0223: The Undefeated granted to % players who lost', v_n; end if;

    -- D · no banner the close minted is a dead key.
    select count(*) into v_n from cosmetics_owned where acquired_at = now()
      and cosmetic_key in ('banner-emberfall', 'banner-emberfall-elite');
    if v_n <> 0 then raise exception '0223: the global close minted % dead banners', v_n; end if;

    raise exception '%', v_marker;
  exception when others then
    get stacked diagnostics v_err = message_text;
    if v_err <> v_marker then raise exception '0223 global-close probe: %', v_err; end if;
  end;

  -- B · the campus close: exactly the board's #1s take Campus Sovereign, and no dead banner.
  begin
    perform set_config('philoi.suppress_push', 'on', true);
    perform snapshot_season_standings('S1');
    perform grant_season_placement_rewards('S1', false);

    select count(*) into v_n from season_standings s
    where s.season_id = 'S1' and s.rank = 1
      and not exists (select 1 from cosmetics_owned co where co.user_id = s.user_id and co.cosmetic_key = 'medal-campus-sovereign');
    if v_n <> 0 then raise exception '0223: % campus #1s missed Campus Sovereign', v_n; end if;
    select count(*) into v_n from cosmetics_owned co
    where co.cosmetic_key = 'medal-campus-sovereign' and co.acquired_at = now()
      and not exists (select 1 from season_standings s where s.season_id = 'S1' and s.rank = 1 and s.user_id = co.user_id);
    if v_n <> 0 then raise exception '0223: Campus Sovereign granted to % players who were not #1', v_n; end if;
    select count(*) into v_n from cosmetics_owned where acquired_at = now() and cosmetic_key = 'banner-emberfall-elite';
    if v_n <> 0 then raise exception '0223: the campus close minted a dead banner'; end if;

    raise exception '%', v_marker;
  exception when others then
    get stacked diagnostics v_err = message_text;
    if v_err <> v_marker then raise exception '0223 campus-close probe: %', v_err; end if;
  end;

  -- B · Hestia on the evaluator, both directions, for everyone who has completed a session.
  begin
    perform set_config('philoi.suppress_push', 'on', true);
    for v_uid in select distinct s.user_id from lock_in_sessions s where s.status = 'completed' loop
      perform economy_evaluate_relics(v_uid);
    end loop;

    select count(*) into v_n from profiles p
    where p.longest_streak >= 30
      and exists (select 1 from lock_in_sessions s where s.user_id = p.id and s.status = 'completed')
      and not exists (select 1 from cosmetics_owned co where co.user_id = p.id and co.cosmetic_key = 'relic-hestias-hearthstone');
    if v_n <> 0 then raise exception '0223: % players with a 30-day streak missed Hestia', v_n; end if;
    select count(*) into v_m from cosmetics_owned co join profiles p on p.id = co.user_id
    where co.cosmetic_key = 'relic-hestias-hearthstone' and co.acquired_at = now() and coalesce(p.longest_streak, 0) < 30;
    if v_m <> 0 then raise exception '0223: Hestia granted to % players under a 30-day streak', v_m; end if;

    raise exception '%', v_marker;
  exception when others then
    get stacked diagnostics v_err = message_text;
    if v_err <> v_marker then raise exception '0223 evaluator probe: %', v_err; end if;
  end;
end;
