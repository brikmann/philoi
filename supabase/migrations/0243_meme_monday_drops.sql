-- ─────────────────────────── 2 · the schedule ───────────────────────────

create table if not exists public.meme_drop_schedule (
  item_key     text primary key references public.cosmetic_rarity (cosmetic_key),
  price_embers integer not null check (price_embers > 0),
  unlocks_at   timestamptz not null,
  ends_at      timestamptz not null,
  constraint meme_drop_window check (ends_at > unlocks_at),
  -- The four slots a drop can be worn in. The key's prefix IS the slot (buy_meme_drop relies on it).
  constraint meme_drop_key check (item_key ~ '^(flame|flare|halo|banner)-meme-')
);

comment on table public.meme_drop_schedule is
  'Meme Monday drops (0243). An item is ember-buyable via buy_meme_drop only inside [unlocks_at, ends_at).';

alter table public.meme_drop_schedule enable row level security;

drop policy if exists meme_drop_schedule_read on public.meme_drop_schedule;
create policy meme_drop_schedule_read on public.meme_drop_schedule
  for select to authenticated using (true);

-- Read-only from the client. Writes happen in migrations (or as postgres), never through the API.
revoke all on public.meme_drop_schedule from public, anon, authenticated;
grant select on public.meme_drop_schedule to authenticated;

-- ─────────────────────────── 3 · buying a drop ───────────────────────────

create or replace function public.buy_meme_drop(p_key text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user uuid := auth.uid();
  v_drop meme_drop_schedule%rowtype;
begin
  if v_user is null then raise exception 'Not signed in'; end if;

  select * into v_drop from meme_drop_schedule where item_key = p_key;
  if not found then raise exception 'That item is not a Meme Monday drop'; end if;
  if now() < v_drop.unlocks_at then raise exception 'This drop has not opened yet'; end if;
  if now() >= v_drop.ends_at then raise exception 'This drop has ended'; end if;

  if exists (select 1 from cosmetics_owned where user_id = v_user and cosmetic_key = p_key) then
    raise exception 'You already own this';
  end if;

  perform economy_move_embers(v_user, -v_drop.price_embers, 'shop_spend', null);
  insert into cosmetics_owned (user_id, cosmetic_key, slot, source, provenance)
  values (v_user, p_key, split_part(p_key, '-', 1), 'paid', 'Meme Monday drop');
  return jsonb_build_object('cosmetic_key', p_key, 'spent', v_drop.price_embers);
end;
$$;

revoke execute on function public.buy_meme_drop(text) from public, anon;
grant execute on function public.buy_meme_drop(text) to authenticated;

-- ─────────────────────────── 4 · buy_cosmetic sells only the box pool ───────────────────────────
-- Same signature (create or replace keeps its grants), same body as 0064 plus the one guard.

create or replace function public.buy_cosmetic(p_key text, p_slot text, p_rarity text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user uuid := auth.uid();
  v_price int;
begin
  if v_user is null then raise exception 'Not signed in'; end if;
  if exists (select 1 from cosmetics_owned where user_id = v_user and cosmetic_key = p_key) then
    raise exception 'You already own this';
  end if;
  if not exists (select 1 from box_droppable_items where item_key = p_key and rarity = p_rarity) then
    raise exception 'That item is not for sale';
  end if;

  v_price := ((select value from economy_config where key = 'direct_buy_price') ->> p_rarity)::int;
  perform economy_move_embers(v_user, -v_price, 'shop_spend', null);
  insert into cosmetics_owned (user_id, cosmetic_key, slot, source, provenance)
  values (v_user, p_key, p_slot, 'paid', 'Bought in the Forge Shop');
  return jsonb_build_object('cosmetic_key', p_key, 'spent', v_price);
end;
$$;

