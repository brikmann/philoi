-- ─────────────────────────── self-check ───────────────────────────

do $assert$
begin
  if (select count(*) from cosmetic_rarity where cosmetic_key like '%-meme-%') <> 7 then
    raise exception '0243: expected 7 meme rows in cosmetic_rarity';
  end if;
  if (select count(*) from meme_drop_schedule) < 2 then
    raise exception '0243: expected the two scheduled drops';
  end if;
  if has_function_privilege('anon', 'public.buy_meme_drop(text)', 'execute') then
    raise exception '0243: anon can execute buy_meme_drop';
  end if;
  if not has_function_privilege('authenticated', 'public.buy_meme_drop(text)', 'execute') then
    raise exception '0243: authenticated cannot execute buy_meme_drop';
  end if;
  if not has_function_privilege('authenticated', 'public.buy_cosmetic(text, text, text)', 'execute') then
    raise exception '0243: buy_cosmetic lost its authenticated grant';
  end if;
  if (select count(*) from pg_proc p join pg_namespace n on n.oid = p.pronamespace
       where n.nspname = 'public' and p.proname in ('buy_cosmetic', 'buy_meme_drop')) <> 2 then
    raise exception '0243: expected exactly one buy_cosmetic and one buy_meme_drop';
  end if;
  if has_table_privilege('authenticated', 'public.meme_drop_schedule', 'insert')
     or has_table_privilege('anon', 'public.meme_drop_schedule', 'select') then
    raise exception '0243: meme_drop_schedule grants are wider than select-for-authenticated';
  end if;
end;
$assert$;
