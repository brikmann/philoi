-- WHAT THIS ADDS (additive — no existing row, item, loadout or balance is touched):
--
--   1. cosmetic_rarity re-seed. Against 0239: + flame-meme-locked-in, + flame-meme-main-character,
--      + flare-meme-aura-1000, + halo-meme-rizz, + halo-meme-goated, + banner-meme-touch-grass,
--      + banner-meme-caught-in-4k. Upserts only; every existing row keeps its rarity.
--
--   2. meme_drop_schedule — one row per DROP: the item, its ember price, and its window. A drop is
--      buyable only while now() is inside [unlocks_at, ends_at); before that it is a locked date,
--      after it the item is gone (MEME_MONDAY_model.md: exclusivity, no permanent vault). Readable by
--      signed-in users so the shop can show this month's drop, its countdown and the next date.
--
--   3. buy_meme_drop(p_key) — the drops' buy RPC. The SERVER decides the price and the window; the
--      client sends only the key. Same debit + inventory write as buy_cosmetic (economy_move_embers
--      'shop_spend', a cosmetics_owned row with source 'paid'), so salvage and the ledger treat a
--      drop like any other bought item.
--
--   4. buy_cosmetic hardened. Until now it priced a buy off the rarity the CLIENT sent and checked
--      nothing about the key — a crafted call could buy any item (an earned relic, a Pass-exclusive,
--      a drop outside its week) at the common price. It now sells only box-pool items
--      (box_droppable_items) at the rarity the server holds for them. Signature, grants and every
--      honest call are unchanged: on 2026-10-15 prod's box_droppable_items matched the app's box
--      pool key-for-key and rarity-for-rarity (63 rows, both EXCEPTs empty, positive control 1 row),
--      so no installed build loses a legitimate buy.
--
--   5. The first two drops: Locked In (Mon 2 Nov 2026) and +1000 Aura (Mon 7 Dec 2026), each live
--      for one week from midnight Toronto time. The other five items are the backlog: catalogued,
--      unscheduled, unsellable until a row is added here.
--
-- NOT HERE, deliberately: no ember grants or balance writes, no push or notify, no change to
-- equip_cosmetic / equipped_loadout / box_droppable_items. Drops never enter the box pool.
--
-- Installed 1.0 builds don't know the seven keys: useInventory and the loadout store skip unknown
-- keys, and banners fall back to Hearthlight, so an old build simply doesn't show them.

